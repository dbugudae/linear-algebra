# A 2D vector has two components.
# Here, x = 3 and y = 4.
vector = [3, 4]

print(vector)


# Python indexing starts at 0, not 1.
# vector[0] accesses the first component (x = 3).
print("First vector component (x):", vector[0])\
# vector[1] accesses the second component (y = 4).
print("Second vector component (y):", vector[1])



# Create a new 2D vector for practice.
new_vector = [3, 4]

# Change the first component (x) from 3 to 6.
new_vector[0] = 6

# Print the updated vector in a readable format.
print("Updated vector:", new_vector)
