
# Define two 2D vectors
vector_a = [2, 3]
vector_b = [4, 1]

# Display both vectors
print("Vector A:", vector_a)
print("Vector B:", vector_b)


# Add the first (x) components of both vectors
x_sum = vector_a[0] + vector_b[0]
print("Sum of X components:", x_sum)


# Add the second (y) components of both vectors
# vector_a[1] = 3 and vector_b[1] = 1
y_sum = vector_a[1] + vector_b[1]
print("Sum of Y components:", y_sum)



# Combine the X and Y sums into one resultant vector
result_vector = [x_sum, y_sum]

# Display the final vector addition result
print("Resultant vector (A + B):", result_vector)

